const plural = (n: number, one: string, many: string) => (n === 1 ? one : many);

/** 950 · 12.4k · 1.2M, with the locale's decimal separator. Deterministic, so server and client agree. */
export function compactNumber(n: number, locale: Locale) {
  const text =
    n < 1000 ? String(Math.round(n)) : n < 1e6 ? `${(n / 1e3).toFixed(n < 1e4 ? 1 : 0)}k` : `${(n / 1e6).toFixed(n < 1e7 ? 2 : 1)}M`;
  return locale === "de" ? text.replace(".", ",") : text;
}

