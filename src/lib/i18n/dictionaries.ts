export const DICTIONARIES: Record<Locale, Dictionary> = { en, de };

/** Localized role, tagline and areas for an agent, falling back to the roster's English. */
export function agentCopy(t: Dictionary, agent: { id: string; role: string; tagline: string; owns: string[] }): AgentCopy {
  return t.agents[agent.id] ?? { role: agent.role, tagline: agent.tagline, owns: agent.owns };
}

/** Relative time ("3 min ago", "vor 3 Min.") using the platform's own translations. */
export function relativeTime(iso: string, locale: Locale, now = Date.now()) {
  const seconds = Math.round((now - new Date(iso).getTime()) / 1000);
  if (seconds < 45) return DICTIONARIES[locale].time.justNow;
  const rtf = new Intl.RelativeTimeFormat(locale, { numeric: "auto", style: "short" });
  const mins = Math.round(seconds / 60);
  if (mins < 60) return rtf.format(-mins, "minute");
  const hours = Math.round(mins / 60);
  if (hours < 24) return rtf.format(-hours, "hour");
  const days = Math.round(hours / 24);
  if (days < 7) return rtf.format(-days, "day");
  return new Date(iso).toLocaleDateString(locale, { month: "short", day: "numeric" });
}

export function clockTime(iso: string, locale: Locale) {
  return new Date(iso).toLocaleTimeString(locale, { hour: "2-digit", minute: "2-digit" });
}
